// Repo-hygiene guard (task 7). ADR 0003: the repo holds only our own work, never stock tags, extracted data, built
// maps, tool binaries or generated build output, and no machine-specific paths (CLAUDE.md: those go only in the
// git-ignored tools/local.config.ps1).

export interface Violation {
  path: string;
  rule: string;
  detail: string;
}

/** File types that must never be committed: built maps, game data, binaries, generated level output. */
const FORBIDDEN_EXTENSIONS = [
  '.map', '.yelo', '.jms', '.wrl', '.scenario_structure_bsp', '.bitmap', '.weapon', '.projectile', '.effect',
  '.exe', '.dll', '.7z', '.zip', '.iso', '.xiso', '.xbe', '.blend1',
];

/** Generated by the world generator (art/launch_lab_arena.py) or the build; rebuilt, never committed. */
const GENERATED_FILES = [
  'mod/data/levels/launch_lab/world_layout.json',
  'mod/data/levels/launch_lab/scripts/world.hsc',
];

/** The only place our tags may live, and the only hand-authored tag type we commit (ADR 0004). */
const OUR_TAGS_DIR = 'mod/tags/levels/launch_lab/';
const COMMITTED_TAG_EXTENSIONS = ['.scenario'];

/** Top-level folders that would mean stock content was copied into the repo. */
const STOCK_ROOTS = ['tags/', 'data/', 'maps/'];

/** Text files that are scanned for machine-specific paths. */
const TEXT_EXTENSIONS = ['.md', '.ps1', '.py', '.hsc', '.json', '.ts', '.yml', '.yaml', '.txt', '.gitignore', '.gitattributes'];

/** Absolute local paths: user folders and the Steam install. ($env:LOCALAPPDATA and the like are fine.) */
const LOCAL_PATH_PATTERNS: Array<[RegExp, string]> = [
  [/[A-Za-z]:\\Users\\/, 'a Windows user folder (C:\\Users\\...)'],
  [/[A-Za-z]:\/Users\//, 'a Windows user folder (C:/Users/...)'],
  [/\/c\/Users\//i, 'a Git Bash user folder (/c/Users/...)'],
  [/steamapps/i, 'a Steam install path (steamapps)'],
];

/** The guard's own source and tests name these patterns on purpose. */
const SELF = ['ci/src/guard.ts', 'ci/test/guard.test.ts'];

function extensionOf(path: string): string {
  const name = path.split('/').pop() ?? path;
  if (name.startsWith('.') && !name.slice(1).includes('.')) return name;   // dotfiles such as .gitignore
  const dot = name.lastIndexOf('.');
  return dot >= 0 ? name.slice(dot).toLowerCase() : '';
}

/** Rules that depend only on a file's path. Paths are repo-relative with forward slashes. */
export function checkPath(path: string): Violation[] {
  const out: Violation[] = [];
  const ext = extensionOf(path);
  if (FORBIDDEN_EXTENSIONS.includes(ext)) {
    out.push({ path, rule: 'forbidden-file-type', detail: `${ext} files are build output or game data (ADR 0003)` });
  }
  if (GENERATED_FILES.includes(path)) {
    out.push({ path, rule: 'generated-file', detail: 'generated by the world generator; rebuild it, never commit it' });
  }
  if (STOCK_ROOTS.some((root) => path.startsWith(root))) {
    out.push({ path, rule: 'stock-content', detail: 'top-level tags/, data/ or maps/ means stock content was copied in' });
  }
  if (path.startsWith('mod/tags/')) {
    if (!path.startsWith(OUR_TAGS_DIR)) {
      out.push({ path, rule: 'tag-outside-our-folder', detail: `our tags live only under ${OUR_TAGS_DIR}` });
    } else if (!COMMITTED_TAG_EXTENSIONS.includes(ext)) {
      out.push({ path, rule: 'uncommitted-tag-type', detail: `only ${COMMITTED_TAG_EXTENSIONS.join(', ')} tags are committed; others are generated` });
    }
  }
  if (path === 'tools/local.config.ps1') {
    out.push({ path, rule: 'local-config', detail: 'machine-specific paths: this file must stay git-ignored' });
  }
  return out;
}

/** Rules that need a text file's content. */
export function checkContent(path: string, text: string): Violation[] {
  if (!TEXT_EXTENSIONS.includes(extensionOf(path)) || SELF.includes(path)) return [];
  const out: Violation[] = [];
  text.split(/\r?\n/).forEach((line, i) => {
    for (const [pattern, what] of LOCAL_PATH_PATTERNS) {
      if (pattern.test(line)) {
        out.push({ path, rule: 'local-path', detail: `line ${i + 1} contains ${what}` });
      }
    }
  });
  return out;
}
